export class I18n {
  constructor(initialLang = 'ru') {
    this.lang = 'ru';
    this.setLang(initialLang);
  }

  setLang(code) {
    const clean = String(code || 'ru').slice(0, 2).toLowerCase();
    this.lang = SUPPORTED_LANGS.includes(clean) ? clean : 'ru';
    if (typeof document !== 'undefined') {
      document.documentElement.lang = this.lang;
    }
    return this.lang;
  }

  cycleLang() {
    const idx = SUPPORTED_LANGS.indexOf(this.lang);
    return this.setLang(SUPPORTED_LANGS[(idx + 1) % SUPPORTED_LANGS.length]);
  }

  t(key, params = null) {
    const dict = STRINGS[this.lang] || STRINGS.ru;
    let text = dict[key] ?? STRINGS.ru[key] ?? key;
    if (params && typeof params === 'object') {
      for (const [k, v] of Object.entries(params)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  }

  pick(localizedObj) {
    if (!localizedObj) return '';
    if (typeof localizedObj === 'string') return localizedObj;
    return localizedObj[this.lang] || localizedObj.ru || localizedObj.en || '';
  }
}
